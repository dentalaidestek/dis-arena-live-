import {createRoot} from 'react-dom/client';
import {arenaRoute} from './routes';
import {Viewer} from './Viewer';
import {AdminPanel} from './AdminPanel';
import './style.css';
import './presentation.css';
import './broadcast.css';
import './clinic.css';
const route=arenaRoute(location.pathname,location.search);
const setup=new URLSearchParams(location.hash.slice(1)).get('setup');
if(setup&&route.page!=='admin')location.replace('/admin?mode='+route.mode+location.hash);
else createRoot(document.getElementById('root')!).render(route.page==='admin'?<AdminPanel initialMode={route.mode}/>:<Viewer mode={route.mode} obs={route.obs}/>);
